SELECT COUNT(*) AS public_orgs
FROM GAFAIG_DB.CORE.V_REGISTRY_PUBLIC;

SELECT COUNTRY, COUNT(*) AS org_count
FROM GAFAIG_DB.CORE.V_REGISTRY_PUBLIC
GROUP BY COUNTRY
ORDER BY org_count DESC, COUNTRY;

SELECT COUNT(DISTINCT COUNTRY) AS countries_represented
FROM GAFAIG_DB.CORE.V_REGISTRY_PUBLIC
WHERE COUNTRY IS NOT NULL;

SELECT
  r.COUNTRY,
  COUNT(*) AS system_count
FROM GAFAIG_DB.CORE.V_REGISTRY_AI_SYSTEMS_PUBLIC s
LEFT JOIN GAFAIG_DB.CORE.V_REGISTRY_PUBLIC r
  ON s.REGISTRY_ID = r.REGISTRY_ID
GROUP BY r.COUNTRY
ORDER BY system_count DESC, r.COUNTRY;

SELECT COUNTRY, COUNT(*) AS application_count
FROM GAFAIG_DB.CORE.APPLICATIONS
GROUP BY COUNTRY
ORDER BY application_count DESC, COUNTRY;