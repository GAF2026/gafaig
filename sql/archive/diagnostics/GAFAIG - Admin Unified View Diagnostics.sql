USE ROLE ACCOUNTADMIN;
USE WAREHOUSE GAFAIG_WH;
USE DATABASE GAFAIG_DB;
USE SCHEMA CORE;

SELECT SOURCE_TABLE, COUNT(*) AS N
FROM CORE.V_ADMIN_SUBMISSIONS
GROUP BY SOURCE_TABLE
ORDER BY SOURCE_TABLE;

SELECT REQUEST_ID, TYPE, STATUS, ORG_NAME, CONTACT_EMAIL, UPDATED_AT, SOURCE_TABLE
FROM CORE.V_ADMIN_SUBMISSIONS
ORDER BY UPDATED_AT DESC NULLS LAST
LIMIT 25;

SHOW DATABASES LIKE 'GAFAIG_DB';
SHOW WAREHOUSES LIKE 'GAFAIG_WH';
SHOW SCHEMAS IN DATABASE GAFAIG_DB LIKE 'CORE';
SHOW VIEWS LIKE 'V_ADMIN_SUBMISSIONS';