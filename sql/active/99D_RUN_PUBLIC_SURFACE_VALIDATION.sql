-- =========================================================
-- 08. PUBLIC SURFACE VERIFICATION-SAFE CONTRACT VALIDATION
-- =========================================================

SELECT
  'REGISTRY_PUBLIC_VERIFICATION_CONTRACT_CHECK' AS VALIDATION_NAME,
  COUNT(*) AS BAD_ROWS
FROM CORE.V_REGISTRY_PUBLIC
WHERE REGISTRY_ID IS NULL
   OR CERTIFICATION_STATUS IS NULL
   OR VISIBILITY_STATUS IS NULL
   OR PUBLISHED_AT IS NULL;

SELECT
  'REGISTRY_PUBLIC_DUPLICATE_REGISTRY_ID_CHECK' AS VALIDATION_NAME,
  COUNT(*) AS BAD_ROWS
FROM (
  SELECT
    REGISTRY_ID,
    COUNT(*) AS ROW_COUNT
  FROM CORE.V_REGISTRY_PUBLIC
  GROUP BY REGISTRY_ID
  HAVING COUNT(*) > 1
);

SELECT
  'REGISTRY_AI_SYSTEMS_PUBLIC_DUPLICATE_SYSTEM_CHECK' AS VALIDATION_NAME,
  COUNT(*) AS BAD_ROWS
FROM (
  SELECT
    REGISTRY_ID,
    SYSTEM_ID,
    COUNT(*) AS ROW_COUNT
  FROM CORE.V_REGISTRY_AI_SYSTEMS_PUBLIC
  GROUP BY REGISTRY_ID, SYSTEM_ID
  HAVING COUNT(*) > 1
);

