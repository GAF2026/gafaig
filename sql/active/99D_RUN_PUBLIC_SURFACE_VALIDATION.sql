-- 06. PUBLIC SURFACE PUBLICATION ENFORCEMENT VALIDATION
-- =========================================================

SELECT
  'REGISTRY_PUBLIC_VISIBILITY_CHECK' AS VALIDATION_NAME,
  COUNT(*) AS BAD_ROWS
FROM CORE.V_REGISTRY_PUBLIC
WHERE COALESCE(VISIBILITY_STATUS, '') <> 'public'
   OR PUBLISHED_AT IS NULL;

