-- =========================================================
-- 10. BATCH D PASS / FAIL SUMMARY
-- =========================================================

WITH CHECKS AS (

  SELECT
    'REGISTRY_PUBLIC_VISIBILITY' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM CORE.V_REGISTRY_PUBLIC
  WHERE COALESCE(VISIBILITY_STATUS, '') <> 'public'
     OR PUBLISHED_AT IS NULL

  UNION ALL

  SELECT
    'REGISTRY_AI_SYSTEMS_PUBLIC_MISSING_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM CORE.V_REGISTRY_AI_SYSTEMS_PUBLIC
  WHERE REGISTRY_ID IS NULL

  UNION ALL

  SELECT
    'LIFECYCLE_PUBLIC_MISSING_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM CORE.V_LIFECYCLE_PUBLIC
  WHERE REGISTRY_ID IS NULL

  UNION ALL

  SELECT
    'RENEWAL_PUBLIC_MISSING_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM CORE.V_RENEWAL_PUBLIC
  WHERE REGISTRY_ID IS NULL

  UNION ALL

  SELECT
    'REGISTRY_PUBLIC_PRIVATE_ID_LEAK' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM GAFAIG_DB.INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = 'CORE'
    AND TABLE_NAME = 'V_REGISTRY_PUBLIC'
    AND COLUMN_NAME IN (
      'APPLICATION_ID',
      'CASE_ID',
      'FINDING_ID',
      'EVIDENCE_ID',
      'INTERNAL_SCORE',
      'FINAL_SCORE',
      'SCORE',
      'TIER',
      'BAND'
    )

  UNION ALL

  SELECT
    'PUBLIC_OBSERVABILITY_AI_COLUMN_LEAK' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM GAFAIG_DB.INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = 'CORE'
    AND TABLE_NAME IN (
      'V_LIFECYCLE_PUBLIC',
      'V_RENEWAL_PUBLIC',
      'V_OBSERVABILITY_PUBLIC'
    )
    AND COLUMN_NAME LIKE 'AI_%'

  UNION ALL

  SELECT
    'REGISTRY_PUBLIC_VERIFICATION_CONTRACT' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM CORE.V_REGISTRY_PUBLIC
  WHERE REGISTRY_ID IS NULL
     OR CERTIFICATION_STATUS IS NULL
     OR VISIBILITY_STATUS IS NULL
     OR PUBLISHED_AT IS NULL

  UNION ALL

  SELECT
    'REGISTRY_PUBLIC_DUPLICATE_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM (
    SELECT
      REGISTRY_ID,
      COUNT(*) AS ROW_COUNT
    FROM CORE.V_REGISTRY_PUBLIC
    GROUP BY REGISTRY_ID
    HAVING COUNT(*) > 1
  )

  UNION ALL

  SELECT
    'REGISTRY_AI_SYSTEMS_PUBLIC_DUPLICATE_SYSTEM' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM (
    SELECT
      REGISTRY_ID,
      SYSTEM_ID,
      COUNT(*) AS ROW_COUNT
    FROM CORE.V_REGISTRY_AI_SYSTEMS_PUBLIC
    GROUP BY REGISTRY_ID, SYSTEM_ID
    HAVING COUNT(*) > 1
  )

  UNION ALL

  SELECT
    'LIFECYCLE_PUBLIC_DUPLICATE_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM (
    SELECT
      REGISTRY_ID,
      COUNT(*) AS ROW_COUNT
    FROM CORE.V_LIFECYCLE_PUBLIC
    GROUP BY REGISTRY_ID
    HAVING COUNT(*) > 1
  )

  UNION ALL

  SELECT
    'RENEWAL_PUBLIC_DUPLICATE_REGISTRY_ID' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM (
    SELECT
      REGISTRY_ID,
      COUNT(*) AS ROW_COUNT
    FROM CORE.V_RENEWAL_PUBLIC
    GROUP BY REGISTRY_ID
    HAVING COUNT(*) > 1
  )

  UNION ALL

  SELECT
    'OBSERVABILITY_PUBLIC_VIEW_AVAILABLE' AS CHECK_NAME,
    CASE
      WHEN COUNT(*) = 0 THEN 1
      ELSE 0
    END AS BAD_ROWS
  FROM GAFAIG_DB.INFORMATION_SCHEMA.VIEWS
  WHERE TABLE_SCHEMA = 'CORE'
    AND TABLE_NAME = 'V_OBSERVABILITY_PUBLIC'

  UNION ALL

  SELECT
    'OBSERVABILITY_PUBLIC_PRIVATE_ID_COLUMN_LEAK' AS CHECK_NAME,
    COUNT(*) AS BAD_ROWS
  FROM GAFAIG_DB.INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = 'CORE'
    AND TABLE_NAME = 'V_OBSERVABILITY_PUBLIC'
    AND COLUMN_NAME IN (
      'APPLICATION_ID',
      'CASE_ID',
      'FINDING_ID',
      'EVIDENCE_ID',
      'INTERNAL_SCORE',
      'FINAL_SCORE',
      'SCORE',
      'TIER',
      'BAND'
    )

)

SELECT
  CHECK_NAME,
  BAD_ROWS,
  CASE
    WHEN BAD_ROWS = 0 THEN 'PASS'
    ELSE 'FAIL'
  END AS STATUS
FROM CHECKS;

