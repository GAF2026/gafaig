  V_EXISTS NUMBER;
BEGIN
  V_ACTOR := COALESCE(P_ACTOR, CURRENT_USER());
  V_NOTES := COALESCE(P_NOTES, ''Unpublish'');

  SELECT COUNT(*)
    INTO :V_EXISTS
  FROM CORE.VERIFICATION_CASES
  WHERE CASE_ID = :P_CASE_ID;

  IF (:V_EXISTS = 0) THEN
    RETURN OBJECT_CONSTRUCT(
      ''ok'', FALSE,
      ''error'', ''Case not found'',
      ''caseId'', P_CASE_ID
    );
  END IF;

  UPDATE CORE.VERIFICATION_CASES
     SET STATUS = ''submitted''
   WHERE CASE_ID = :P_CASE_ID;

  -- IMPORTANT: use INSERT...SELECT (avoids UUID_STRING() in VALUES issues)
  INSERT INTO CORE.CASE_APPROVAL_LOG (LOG_ID, CASE_ID, ACTION, ACTOR, ACTION_AT, NOTES)
  SELECT
    UUID_STRING(),
    :P_CASE_ID,
    ''UNAPPROVE'',
    :V_ACTOR,
    CURRENT_TIMESTAMP(),
    :V_NOTES;

  RETURN OBJECT_CONSTRUCT(
    ''ok'', TRUE,
    ''caseId'', P_CASE_ID,
    ''actor'', V_ACTOR,
    ''notes'', V_NOTES
  );
END;
';
create or replace row access policy RAP_CASES_BY_ORG as (ORG_ID VARCHAR) 
returns BOOLEAN ->
(
    -- Regulators see everything
    IS_ROLE_IN_SESSION('GAFAIG_REGULATOR_ROLE')

    OR

    -- App user only sees mapped orgs
    EXISTS (
        SELECT 1
        FROM USER_ORG_ACCESS ua
        WHERE ua.USERNAME = CURRENT_USER()
          AND ua.ORG_ID = ORG_ID
    )
)
;
