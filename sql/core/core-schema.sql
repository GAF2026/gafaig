CREATE OR REPLACE PROCEDURE "SP_CREATE_CASE"("P_CASE_ID" VARCHAR, "P_PARTICIPANT_ID" VARCHAR, "P_STATUS" VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_ORG STRING;
BEGIN
  SELECT ORG_ID INTO :V_ORG
  FROM GAFAIG_DB.CORE.USER_ORG_ACCESS
  WHERE USERNAME = CURRENT_USER()
  QUALIFY ROW_NUMBER() OVER (ORDER BY ORG_ID) = 1;

  IF (V_ORG IS NULL) THEN
    RETURN OBJECT_CONSTRUCT(''ok'', FALSE, ''error'', ''No ORG mapping for user'', ''user'', CURRENT_USER());
  END IF;

  INSERT INTO GAFAIG_DB.CORE.VERIFICATION_CASES (CASE_ID, PARTICIPANT_ID, ORG_ID, STATUS)
  VALUES (P_CASE_ID, P_PARTICIPANT_ID, V_ORG, P_STATUS);

  RETURN OBJECT_CONSTRUCT(''ok'', TRUE, ''caseId'', P_CASE_ID, ''orgId'', V_ORG);
END;
';
