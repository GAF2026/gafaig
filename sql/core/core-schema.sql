create or replace view V_CASE_CONTROL_SCORE_CALC_V1(
	CASE_ID,
	CONTROL_CODE,
	WEIGHT,
	CONTROL_STATUS,
	EVIDENCE_COUNT,
	HAS_SUMMARY,
	LAST_TESTED_AT,
	STATUS_SCORE,
	CONTROL_POINTS,
	CONTROL_DENOM,
	COVERAGE_FLAG,
	SUMMARY_FLAG
) as
SELECT
  a.CASE_ID,
  a.CONTROL_CODE,
  c.WEIGHT,
  a.CONTROL_STATUS,
  a.EVIDENCE_COUNT,
  a.HAS_SUMMARY,
  a.LAST_TESTED_AT,

  CASE a.CONTROL_STATUS
    WHEN 'met' THEN 1.0
    WHEN 'partial' THEN 0.5
    WHEN 'not_met' THEN 0.0
    ELSE NULL
  END AS STATUS_SCORE,

  (CASE a.CONTROL_STATUS
    WHEN 'met' THEN 1.0
    WHEN 'partial' THEN 0.5
    WHEN 'not_met' THEN 0.0
    ELSE NULL
   END) * c.WEIGHT AS CONTROL_POINTS,

  c.WEIGHT AS CONTROL_DENOM,

  IFF(a.EVIDENCE_COUNT > 0,1.0,0.0) AS COVERAGE_FLAG,
  IFF(a.HAS_SUMMARY,1.0,0.0) AS SUMMARY_FLAG

FROM CASE_CONTROL_ATTESTATIONS a
JOIN STANDARD_CONTROLS c
  ON a.CONTROL_CODE = c.CONTROL_CODE
WHERE a.STANDARD_CODE='HG'
  AND a.STANDARD_VERSION='v1.0';
create or replace view V_CASE_INPUTS(
	CASE_ID,
	FINDINGS_TOTAL,
	FINDINGS_PASS,
	FINDINGS_FAIL,
	FINDINGS_NA,
	FINDINGS_APPLICABLE,
	FINDINGS_COVERED,
	EVIDENCE_TOTAL,
	EVIDENCE_WITH_SUMMARY,
	NEWEST_VALID_EVIDENCE_AT,
	CONTROLS_PCT,
	COVERAGE_PCT,
	SUMMARY_PCT,
	FRESHNESS_PCT
) as
WITH

F AS (
  SELECT
    TRIM(CASE_ID) AS CASE_ID,
    TRIM(FINDING_ID) AS FINDING_ID,
    UPPER(TRIM(RESULT)) AS STATUS
  FROM CORE.VERIFICATION_FINDINGS
),

E AS (
  SELECT
    TRIM(CASE_ID) AS CASE_ID,
    TRIM(EVIDENCE_ID) AS EVIDENCE_ID,
    COALESCE(SUBMITTED_AT, CREATED_AT) AS EVIDENCE_AT
  FROM CORE.VERIFICATION_EVIDENCE
),

S AS (
  SELECT
    TRIM(EVIDENCE_ID) AS EVIDENCE_ID,
    IFF(SUMMARY IS NOT NULL AND LENGTH(TRIM(SUMMARY)) > 0, 1, 0) AS HAS_SUMMARY,
    ROW_NUMBER() OVER (
      PARTITION BY TRIM(EVIDENCE_ID)
      ORDER BY CREATED_AT DESC
    ) AS RN
  FROM CORE.EVIDENCE_SUMMARIES
),

S_LATEST AS (
  SELECT EVIDENCE_ID, HAS_SUMMARY
  FROM S
  WHERE RN = 1
),

M AS (
  SELECT
    TRIM(CASE_ID) AS CASE_ID,
    TRIM(FINDING_ID) AS FINDING_ID,
    TRIM(EVIDENCE_ID) AS EVIDENCE_ID
  FROM CORE.FINDING_EVIDENCE_MAP
),

VALID_EVIDENCE AS (
  SELECT DISTINCT
    m.CASE_ID,
    m.FINDING_ID,
    m.EVIDENCE_ID
  FROM M m
  JOIN S_LATEST s
    ON s.EVIDENCE_ID = m.EVIDENCE_ID
   AND s.HAS_SUMMARY = 1
),

F_COUNTS AS (
  SELECT
    CASE_ID,
    COUNT(*) AS FINDINGS_TOTAL,
    SUM(IFF(STATUS = 'PASS', 1, 0)) AS FINDINGS_PASS,
    SUM(IFF(STATUS = 'FAIL', 1, 0)) AS FINDINGS_FAIL,
    SUM(IFF(STATUS = 'NA',   1, 0)) AS FINDINGS_NA,
    SUM(IFF(STATUS IN ('PASS','FAIL'), 1, 0)) AS FINDINGS_APPLICABLE
  FROM F
  GROUP BY CASE_ID
),

COVERAGE AS (
  SELECT
    f.CASE_ID,
    COUNT(DISTINCT IFF(f.STATUS IN ('PASS','FAIL')
      AND ve.FINDING_ID IS NOT NULL, f.FINDING_ID, NULL)
    ) AS FINDINGS_COVERED
  FROM F f
  LEFT JOIN (SELECT DISTINCT CASE_ID, FINDING_ID FROM VALID_EVIDENCE) ve
    ON ve.CASE_ID = f.CASE_ID
   AND ve.FINDING_ID = f.FINDING_ID
  GROUP BY f.CASE_ID
),

E_COUNTS AS (
  SELECT CASE_ID, COUNT(*) AS EVIDENCE_TOTAL
  FROM E
  GROUP BY CASE_ID
),

E_WITH_SUMMARY AS (
  SELECT
    e.CASE_ID,
    COUNT(DISTINCT e.EVIDENCE_ID) AS EVIDENCE_WITH_SUMMARY
  FROM E e
  JOIN S_LATEST s
    ON s.EVIDENCE_ID = e.EVIDENCE_ID
   AND s.HAS_SUMMARY = 1
  GROUP BY e.CASE_ID
),

NEWEST_VALID AS (
  SELECT
    ve.CASE_ID,
    MAX(e.EVIDENCE_AT) AS NEWEST_VALID_EVIDENCE_AT
  FROM (SELECT DISTINCT CASE_ID, EVIDENCE_ID FROM VALID_EVIDENCE) ve
  JOIN E e
    ON e.CASE_ID = ve.CASE_ID
   AND e.EVIDENCE_ID = ve.EVIDENCE_ID
  GROUP BY ve.CASE_ID
)

SELECT
  fc.CASE_ID,
  fc.FINDINGS_TOTAL,
  fc.FINDINGS_PASS,
  fc.FINDINGS_FAIL,
  fc.FINDINGS_NA,
  fc.FINDINGS_APPLICABLE,
  COALESCE(cv.FINDINGS_COVERED, 0) AS FINDINGS_COVERED,
  COALESCE(ec.EVIDENCE_TOTAL, 0) AS EVIDENCE_TOTAL,
  COALESCE(es.EVIDENCE_WITH_SUMMARY, 0) AS EVIDENCE_WITH_SUMMARY,
  nv.NEWEST_VALID_EVIDENCE_AT,

  IFF(fc.FINDINGS_APPLICABLE = 0, 0,
      (fc.FINDINGS_PASS::FLOAT / fc.FINDINGS_APPLICABLE::FLOAT) * 100
  ) AS CONTROLS_PCT,

  IFF(fc.FINDINGS_APPLICABLE = 0, 0,
      (COALESCE(cv.FINDINGS_COVERED,0)::FLOAT / fc.FINDINGS_APPLICABLE::FLOAT) * 100
  ) AS COVERAGE_PCT,

  IFF(COALESCE(ec.EVIDENCE_TOTAL,0) = 0, 0,
      (COALESCE(es.EVIDENCE_WITH_SUMMARY,0)::FLOAT / ec.EVIDENCE_TOTAL::FLOAT) * 100
  ) AS SUMMARY_PCT,

  CASE
    WHEN nv.NEWEST_VALID_EVIDENCE_AT IS NULL THEN 0
    ELSE
      CASE
        WHEN DATEDIFF('day', nv.NEWEST_VALID_EVIDENCE_AT::DATE, CURRENT_DATE()) BETWEEN 0 AND 90 THEN 100
        WHEN DATEDIFF('day', nv.NEWEST_VALID_EVIDENCE_AT::DATE, CURRENT_DATE()) BETWEEN 91 AND 180 THEN 80
        WHEN DATEDIFF('day', nv.NEWEST_VALID_EVIDENCE_AT::DATE, CURRENT_DATE()) BETWEEN 181 AND 365 THEN 60
        WHEN DATEDIFF('day', nv.NEWEST_VALID_EVIDENCE_AT::DATE, CURRENT_DATE()) BETWEEN 366 AND 730 THEN 40
        ELSE 20
      END
  END AS FRESHNESS_PCT

FROM F_COUNTS fc
LEFT JOIN COVERAGE cv ON cv.CASE_ID = fc.CASE_ID
LEFT JOIN E_COUNTS ec ON ec.CASE_ID = fc.CASE_ID
LEFT JOIN E_WITH_SUMMARY es ON es.CASE_ID = fc.CASE_ID
LEFT JOIN NEWEST_VALID nv ON nv.CASE_ID = fc.CASE_ID
;
